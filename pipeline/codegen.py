"""Writes renderer/src/types.gen.ts and theme.gen.ts from schema.py and theme.py, so Python and TypeScript never drift.
Handles the JSON-schema subset pydantic emits for our models; anything else is an error, not a silent `any`."""

import json
from pathlib import Path
from typing import Any

from pipeline.schema import Timeline
from pipeline.theme import THEME

HEADER = "// Generated by `python -m pipeline gen` from pipeline/{src}. Do not edit.\n"
RENDERER_SRC = Path(__file__).resolve().parent.parent / "renderer" / "src"


def ts_type(s: dict[str, Any]) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            return " | ".join(ts_type(x) for x in s[key])
    t = s.get("type")
    if t == "array":
        inner = ts_type(s["items"])
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object" and "additionalProperties" in s:
        return f"Record<string, {ts_type(s['additionalProperties'])}>"
    simple = {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}
    if t in simple:
        return simple[t]
    raise ValueError(f"codegen does not handle this schema: {s}")


def ts_object(name: str, s: dict[str, Any]) -> str:
    required = set(s.get("required", []))
    lines = [f"export type {name} = {{"]
    for prop, sub in s["properties"].items():
        lines.append(f"  {prop}{'' if prop in required else '?'}: {ts_type(sub)};")
    return "\n".join([*lines, "};"])


def types_ts() -> str:
    schema = Timeline.model_json_schema(mode="serialization")
    parts = [ts_object(n, d) for n, d in sorted(schema.get("$defs", {}).items())]
    parts.append(ts_object("Timeline", schema))
    names = [
        d["properties"]["type"]["const"] for d in schema["$defs"].values() if "const" in d["properties"].get("type", {})
    ]
    parts.append(f"export type ElementType = {' | '.join(json.dumps(n) for n in sorted(names))};")
    return HEADER.format(src="schema.py") + "\n\n".join(parts) + "\n"


def theme_ts() -> str:
    return HEADER.format(src="theme.py") + f"export const THEME = {json.dumps(THEME, indent=2)} as const;\n"


def outputs() -> dict[Path, str]:
    return {RENDERER_SRC / "types.gen.ts": types_ts(), RENDERER_SRC / "theme.gen.ts": theme_ts()}


def write() -> list[Path]:
    for path, text in outputs().items():
        path.write_text(text, encoding="utf-8")
    return list(outputs())
